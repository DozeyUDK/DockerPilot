#!/usr/bin/env python3
"""Generate Python and JavaScript icon maps from a single Nerd Fonts catalog."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "icons" / "catalog.json"
PYTHON = ROOT / "src" / "dockerpilot" / "ui_icons.py"
JAVASCRIPT = ROOT / "DockerPilotExtras" / "frontend" / "src" / "icons.mjs"

def build():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    icons = data["icons"]
    glyphs = {key: chr(int(value["codepoint"], 16)) for key, value in icons.items()}
    fallbacks = {key: value["fallback"] for key, value in icons.items()}
    header = "# Generated by tools/icons/generate.py; do not edit directly.\n"
    py = (
        header
        + '"""Shared Nerd Fonts icon symbols for the Python CLI and TUI."""\n'
        + "import os\n\n"
        + f"GLYPHS = {glyphs!r}\n"
        + f"FALLBACKS = {fallbacks!r}\n\n"
        + "def icon(name: str) -> str:\n"
        + '    """Return a font icon when explicitly enabled; safe ASCII by default.\n\n'
        + '    Set DOCKERPILOT_ICON_MODE=nerd when the client terminal has a Nerd Font.\n'
        + '    """\n'
        + "    mode = os.getenv('DOCKERPILOT_ICON_MODE', 'ascii').lower()\n"
        + "    if mode == 'nerd':\n"
        + "        return GLYPHS[name]\n"
        + "    return FALLBACKS[name]\n"
    )
    js = (
        "// Generated by tools/icons/generate.py; do not edit directly.\n"
        + "export const ICONS = Object.freeze(" + json.dumps(glyphs,ensure_ascii=False,indent=2) + ")\n"
    )
    return {PYTHON: py, JAVASCRIPT: js}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = build()
    if args.check:
        outdated=[str(p.relative_to(ROOT)) for p,v in expected.items() if not p.is_file() or p.read_text(encoding="utf-8")!=v]
        if outdated:
            parser.error("Generated icon maps are stale: "+", ".join(outdated))
        print("Icon catalog generated files match.")
        return
    for path,content in expected.items():
        path.write_text(content,encoding="utf-8")
        print(path.relative_to(ROOT))

if __name__=="__main__":
    main()
